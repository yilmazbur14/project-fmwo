def text_w(s):
    return len(s) * 4 - 1


def draw_text(img, s, x, y, c, scale=1):
    for ch in s:
        g = G35[ch]
        for yy, row in enumerate(g):
            for xx, v in enumerate(row):
                if v == '1':
                    for sy in range(scale):
                        for sx in range(scale):
                            img.set(x + xx * scale + sx, y + yy * scale + sy, c)
        x += 4 * scale
