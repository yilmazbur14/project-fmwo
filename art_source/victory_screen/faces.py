TEMPL = {16: F16, 12: F12, 9: F9}


def face_mask(d):
    r = d / 2.0
    return ellipse_mask(r, r, r, r)


def draw_face(cv, x0, y0, d, expr, depth, lit=False):
    """Draws a round emoji face with top-left at (x0,y0), diameter d."""
    T = dict(TONES[depth])
    if lit:
        T.update(LIT[depth])
    m = face_mask(d)
    edge = inner_edge(m, N4)
    r = d / 2.0
    for (x, y) in m:
        # light from upper-left: shade lower-right crescent, highlight upper-left
        dx, dy = (x + 0.5 - r) / r, (y + 0.5 - r) / r
        c = T['b']
        if dx * 0.55 + dy * 0.85 > 0.42:
            c = T['s']
        if (dx + 0.38) ** 2 + (dy + 0.42) ** 2 < 0.07 and d >= 12:
            c = T['h']
        cv.set(x0 + x, y0 + y, c)
    for (x, y) in edge:
        cv.set(x0 + x, y0 + y, T['o'])
    g = TEMPL[d][expr]
    for j, row in enumerate(g):
        for i, ch in enumerate(row):
            if ch == '.':
                continue
            col = EXTRA.get(ch) or T[ch]
            cv.set(x0 + i, y0 + j, col)
