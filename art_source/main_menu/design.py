"""Hand-cleaned silhouette grids, built from row spans (read off the downscaled sprites).
'#' silhouette, '+' interior contour hint, 'o' glint, 'R' red glow."""
import re, subprocess


def grid(W, H, spans, marks=()):
    g = [['.'] * W for _ in range(H)]
    for y, lst in spans.items():
        for a, b in lst:
            for x in range(a, b + 1):
                if 0 <= x < W and 0 <= y < H:
                    g[y][x] = '#'
    for ch, pts in marks:
        for x, y in pts:
            g[y][x] = ch
    return [''.join(r) for r in g]


def mirror_spans(spans, W):
    return {y: [(W - 1 - b, W - 1 - a) for a, b in lst] for y, lst in spans.items()}


