def text_px(s, colour=(255, 255, 255, 255), scale=1):
    s = s.upper()
    w = max(1, len(s) * 4 - 1)
    img = blank(w, 5)
    for i, ch in enumerate(s):
        g = G.get(ch, G[' '])
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == '#':
                    img[y][i * 4 + x] = colour
    return zoom(img, scale, None) if scale > 1 else img


def draw_text(dst, s, x, y, colour=(255, 255, 255, 255), scale=2):
    t = text_px(s, colour, 1)
    blit_scaled(dst, t, x, y, scale)
