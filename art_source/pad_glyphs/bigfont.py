def _draw(c, rows, x, y, col):
    for gy, row in enumerate(rows):
        for gx, v in enumerate(row):
            if v == '#':
                c.set(x + gx, y + gy, col)


def draw_big(c, ch, x, y, col):
    _draw(c, BIG[ch], x, y, col)


def draw_mid_text(c, text, x, y, col, gap=2):
    """Two-letter shoulder label; returns the x after the last letter."""
    for ch in text:
        _draw(c, MID[ch], x, y, col)
        x += len(MID[ch][0]) + gap
    return x - gap


def draw_mini(c, ch, x, y, col):
    _draw(c, MINI[ch], x, y, col)


def draw_qmark(c, x, y, col):
    _draw(c, QMARK, x, y, col)


def width(font, text, gap):
    return sum(len(font[ch][0]) for ch in text) + gap * (len(text) - 1)
